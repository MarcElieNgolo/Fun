export function respondToQuery(query) {
    const lowerCaseQuery = query.toLowerCase();

    for (const rule of rules) {
        for (const pattern of rule.patterns) {
            if (pattern.test(lowerCaseQuery)) {
                const response = rule.responses[Math.floor(Math.random() * rule.responses.length)];
                return response;
            }
        }
    }
    return "BATI-BOT n'a pas de réponse pour ça. Pouvez-vous être plus précis ? 😕";
}
